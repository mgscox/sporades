import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedHeader = "Generated by `npm run build` from TypeScript sources. Do not edit by hand.";

const bins = [
  path.join(repoRoot, "bin", "sporades.js"),
  path.join(repoRoot, "bin", "sporades-host-helper.js"),
];

for (const file of bins) {
  const contents = await readFile(file, "utf8");
  if (!contents.startsWith("#!/usr/bin/env node\n")) {
    throw new Error(`${path.relative(repoRoot, file)} is missing the Node shebang.`);
  }
  if (!contents.includes(generatedHeader)) {
    throw new Error(`${path.relative(repoRoot, file)} is missing the generated-file header.`);
  }
  if (contents.includes("../src/")) {
    throw new Error(`${path.relative(repoRoot, file)} still imports from ../src.`);
  }
}
