import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(await readFile(path.join(repoRoot, "package.json"), "utf8"));
const version = packageJson.version;

if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`Cannot bake non-semver package version into CLI: ${version}`);
}

await writeFile(
  path.join(repoRoot, "src", "cli", "cli-version.ts"),
  `// Generated by \`npm run build\` from package.json. Do not edit by hand.\nexport const CLI_VERSION = ${JSON.stringify(version)};\n`,
);
